import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "../..");
const appRoot = path.join(root, "lib/shortcuts/apps");
const routeRoot = path.join(root, "app/(site)/(references)/keyboard-shortcuts");
const manifestRoot = path.join(root, "tests/pages/keyboard-shortcuts");
const checkOnly = process.argv.includes("--check");
const changed = [];

function read(file) {
  return readFileSync(file, "utf8");
}

function writeGenerated(file, content) {
  if (existsSync(file) && read(file) === content) return;
  changed.push(path.relative(root, file));
  if (!checkOnly) writeFileSync(file, content);
}

function generatedRoute(slug) {
  return `import app from "@/lib/shortcuts/apps/${slug}";
import { KeyboardShortcutsAppPage } from "../keyboard-shortcuts-app-page";

export default function KeyboardShortcutsPage() {
  return <KeyboardShortcutsAppPage app={app} />;
}
`;
}

function generatedManifest(slug, current) {
  const state = current?.state ?? "noindex";
  const manifest = {
    route: `/keyboard-shortcuts/${slug}`,
    state,
    ...(state === "published"
      ? {}
      : {
          reason:
            current?.reason ??
            "The shortcut record has verified official-source data, but this route remains noindex until its publication review is complete.",
        }),
    docs: current?.docs ?? ["content_docs/keyboard-shortcuts"],
    tests: [
      ...new Set([
        ...(current?.tests ?? [
          "tests/stack127/seo.spec.ts",
          "tests/pages/keyboard-shortcuts/page.test.mjs",
          "tests/pages/keyboard-shortcuts/shared/data.test.mjs",
          "tests/pages/keyboard-shortcuts/keyboard-shortcuts.spec.ts",
        ]),
        "tests/pages/keyboard-shortcuts/shared/generation.test.mjs",
      ]),
    ],
    scripts: [...new Set([...(current?.scripts ?? []), "scripts/keyboard-shortcuts"])],
    skills: current?.skills ?? [
      "skills/stack127/test-driven-page",
      "skills/stack127/visual-first-content",
    ],
    repositories: current?.repositories ?? [],
  };

  return `${JSON.stringify(manifest, null, 2)}\n`;
}

const slugs = readdirSync(appRoot)
  .filter((name) => name.endsWith(".ts"))
  .map((name) => name.slice(0, -3))
  .sort();

const apps = [];
for (const slug of slugs) {
  const module = await import(pathToFileURL(path.join(appRoot, `${slug}.ts`)).href);
  const app = module.default;
  if (!app || app.slug !== slug) {
    throw new Error(`${slug}.ts must default-export its AppShortcuts record.`);
  }
  apps.push(app);
}
apps.sort((left, right) => left.name.localeCompare(right.name));

const catalog = apps.map((app) => ({
  slug: app.slug,
  name: app.name,
  category: app.category,
  platforms: app.platforms,
  shortcutCount: app.groups.reduce((total, group) => total + group.shortcuts.length, 0),
}));

const catalogSource = `import type { PlatformId } from "./types.ts";

export type ShortcutAppSummary = {
  slug: string;
  name: string;
  category: string;
  platforms: readonly PlatformId[];
  shortcutCount: number;
};

/** Compact app metadata for catalogs and navigation. Generated by sync-pages.mjs. */
export const shortcutAppCatalog = ${JSON.stringify(catalog, null, 2)} as const satisfies readonly ShortcutAppSummary[];
`;

const loaderEntries = slugs
  .map((slug) => `  ${JSON.stringify(slug)}: () => import("./apps/${slug}.ts"),`)
  .join("\n");
const loadersSource = `import type { AppShortcuts } from "./types.ts";
import { shortcutAppCatalog } from "./catalog.generated.ts";

/** One dynamic import per app keeps full shortcut tables out of catalogs and sidebars. */
export const shortcutAppLoaders = {
${loaderEntries}
} satisfies Record<string, () => Promise<{ default: AppShortcuts }>>;

export type ShortcutAppSlug = keyof typeof shortcutAppLoaders;

export async function loadShortcutApp(slug: string): Promise<AppShortcuts | undefined> {
  const loader = shortcutAppLoaders[slug as ShortcutAppSlug];
  return loader ? (await loader()).default : undefined;
}

export async function loadShortcutApps(): Promise<AppShortcuts[]> {
  return Promise.all(shortcutAppCatalog.map(async (summary) => {
    const app = await loadShortcutApp(summary.slug);
    if (!app) throw new Error(\`Missing shortcut app module: \${summary.slug}\`);
    return app;
  }));
}
`;

writeGenerated(path.join(root, "lib/shortcuts/catalog.generated.ts"), catalogSource);
writeGenerated(path.join(root, "lib/shortcuts/loaders.generated.ts"), loadersSource);

for (const slug of slugs) {
  const routeDirectory = path.join(routeRoot, slug);
  const manifestDirectory = path.join(manifestRoot, slug);
  if (!checkOnly) {
    await mkdir(routeDirectory, { recursive: true });
    await mkdir(manifestDirectory, { recursive: true });
  }

  writeGenerated(path.join(routeDirectory, "page.tsx"), generatedRoute(slug));

  const manifestFile = path.join(manifestDirectory, "page.json");
  const current = existsSync(manifestFile) ? JSON.parse(read(manifestFile)) : undefined;
  writeGenerated(manifestFile, generatedManifest(slug, current));
}

if (changed.length > 0) {
  if (checkOnly) {
    console.error(`Keyboard shortcut pages are out of sync:\n${changed.join("\n")}`);
    process.exitCode = 1;
  } else {
    console.log(`Updated ${changed.length} keyboard shortcut files.`);
  }
} else {
  console.log("Keyboard shortcut pages are in sync.");
}
