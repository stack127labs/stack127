/**
 * Clean chart generator. Walks app/ for *.chart.json specs and
 * writes <name>.svg next to each spec, plus <name>.ts (the SVG exported as a
 * string for bundling) for specs under app/. Same architecture as the
 * marker-art generator; see stack127_docs/design-system.md.
 *
 * Run with: npm run stack127:clean-charts
 * Or with explicit spec paths as arguments.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, relative } from "node:path";
import { Canvas } from "./svg.mjs";
import { FIGURES } from "./figures.mjs";

const root = process.cwd();

function* walk(dir) {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry.startsWith(".")) continue;
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* walk(full);
    else if (entry.endsWith(".chart.json")) yield full;
  }
}

function validate(spec, file) {
  const errors = [];
  for (const field of ["id", "type", "takeaway", "source", "dataAsOf"]) {
    if (!spec[field]) errors.push(`${file}: missing required field "${field}"`);
  }
  if (spec.type && !FIGURES[spec.type]) {
    errors.push(`${file}: unknown chart type "${spec.type}" (have: ${Object.keys(FIGURES).join(", ")})`);
  }
  if (!spec.data) errors.push(`${file}: missing "data"`);
  return errors;
}

const camel = (name) =>
  name.replace(/[^a-zA-Z0-9]+(\w)/g, (_, c) => c.toUpperCase()).replace(/[^a-zA-Z0-9]/g, "");

const specs = process.argv.length > 2
  ? process.argv.slice(2)
  : [...walk(join(root, "app"))];

let failed = false;

for (const file of specs) {
  const rel = relative(root, file);
  try {
    const spec = JSON.parse(readFileSync(file, "utf8"));
    const errors = validate(spec, rel);
    if (errors.length) throw new Error(errors.join("\n"));

    const canvas = new Canvas(spec);
    FIGURES[spec.type](spec, canvas);
    const svg = canvas.serialize();

    const name = basename(file, ".chart.json");
    const dir = dirname(file);
    writeFileSync(join(dir, `${name}.svg`), svg + "\n");

    if (rel.startsWith("app")) {
      const exportName = `${camel(name)}Chart`;
      writeFileSync(
        join(dir, `${name}.ts`),
        `// generated by scripts/stack127/clean-charts/generate.mjs. do not edit.\n` +
          `// edit the sibling .chart.json and rerun: npm run stack127:clean-charts\n` +
          `export const ${exportName} = \`${svg.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${")}\`;\n`,
      );
      console.log(`\u2713 ${rel} -> ${name}.svg + ${name}.ts`);
    } else {
      console.log(`\u2713 ${rel} -> ${name}.svg`);
    }
  } catch (error) {
    failed = true;
    console.error(`\u2717 ${rel}: ${error.message}`);
  }
}

if (failed) process.exit(1);
