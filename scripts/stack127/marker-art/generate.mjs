/**
 * Marker art generator. Turns *.spec.json files into final SVGs at build time.
 *
 * Usage:
 *   node scripts/stack127/marker-art/generate.mjs               # all specs in app/ and dev-space/
 *   node scripts/stack127/marker-art/generate.mjs <path...>     # specific spec files or dirs
 *   node scripts/stack127/marker-art/generate.mjs --index <dir> # also write a showcase index.html
 *
 * Outputs, next to each spec:
 *   <name>.svg  the canonical artifact (open it, review it, commit it)
 *   <name>.ts   the same SVG as an exported string, for zero-runtime inlining
 *               (.ts is only written for specs under app/)
 *
 * Style guide: stack127_docs/marker-art.md
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, basename, relative } from "node:path";
import { Art } from "./svg.mjs";
import { FIGURES } from "./figures.mjs";
import { validateSpec, lintRender } from "./lint.mjs";

const ROOT = process.cwd();

function findSpecs(dir) {
  const out = [];
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.name === "node_modules" || e.name.startsWith(".")) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...findSpecs(p));
    else if (e.name.endsWith(".spec.json")) out.push(p);
  }
  return out;
}

function camel(name) {
  return name.replace(/[-_ ]+(\w)/g, (_, c) => c.toUpperCase());
}

function tsModule(svg, exportName) {
  const escaped = svg.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return (
    `// generated by scripts/stack127/marker-art/generate.mjs. do not edit.\n` +
    `// edit the sibling .spec.json and rerun: npm run stack127:marker-art\n` +
    `export const ${exportName} = \`${escaped}\`;\n`
  );
}

function indexHtml(figures) {
  const cards = figures
    .map(
      (f) =>
        `<div class="fig"><h4>${f.id} · ${f.type}</h4>${f.svg}<p>${f.takeaway}</p></div>`,
    )
    .join("\n");
  return `<!doctype html><html><head><meta charset="utf-8"><title>marker art showcase</title>
<link href="https://fonts.googleapis.com/css2?family=Shantell+Sans:wght@500;700&display=swap" rel="stylesheet">
<style>
body{background:#0a0a0a;color:#ececec;font-family:ui-sans-serif,system-ui;margin:0;padding:32px}
:root{--font-marker:'Shantell Sans'}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(340px,1fr));gap:16px;max-width:1280px;margin:0 auto}
.fig{background:#111;border:1px solid rgba(255,255,255,.1);border-radius:12px;padding:14px}
.fig h4{margin:0 0 8px;font:600 10.5px ui-monospace;letter-spacing:.09em;text-transform:uppercase;color:#8b8b8b}
.fig svg{width:100%;height:auto;display:block}
.fig p{color:#9a9a9a;font-size:.82rem;margin:8px 0 0}
</style></head><body><div class="grid">${cards}</div></body></html>`;
}

function main() {
  const args = process.argv.slice(2);
  const wantIndex = args.includes("--index");
  const paths = args.filter((a) => a !== "--index");
  let specFiles = [];
  if (paths.length === 0) {
    specFiles = [...findSpecs(join(ROOT, "app")), ...findSpecs(join(ROOT, "dev-space"))];
  } else {
    for (const p of paths) {
      const full = join(ROOT, p);
      specFiles.push(...(statSync(full).isDirectory() ? findSpecs(full) : [full]));
    }
  }
  if (specFiles.length === 0) {
    console.log("no *.spec.json files found");
    return;
  }

  let failed = false;
  const byDir = {};
  for (const file of specFiles) {
    const rel = relative(ROOT, file);
    let spec;
    try {
      spec = JSON.parse(readFileSync(file, "utf8"));
    } catch (e) {
      console.error(`✗ ${rel}: invalid JSON (${e.message})`);
      failed = true;
      continue;
    }
    const v = validateSpec(spec, rel);
    if (v.errors.length) {
      v.errors.forEach((e) => console.error(`✗ ${e}`));
      failed = true;
      continue;
    }
    const A = new Art(spec);
    try {
      FIGURES[spec.type](spec, A);
    } catch (e) {
      console.error(`✗ ${rel}: draw failed: ${e.message}`);
      failed = true;
      continue;
    }
    const l = lintRender(A, rel);
    l.warnings.concat(v.warnings).forEach((w) => console.warn(`! ${w}`));
    if (l.errors.length) {
      l.errors.forEach((e) => console.error(`✗ ${e}`));
      failed = true;
      continue;
    }
    const svg = A.serialize();
    const dir = dirname(file);
    const name = basename(file).replace(/\.spec\.json$/, "");
    writeFileSync(join(dir, `${name}.svg`), svg + "\n");
    const isApp = rel.startsWith("app/") || rel.startsWith("app\\");
    if (isApp) {
      writeFileSync(join(dir, `${name}.ts`), tsModule(svg, `${camel(name)}Art`));
    }
    (byDir[dir] ||= []).push({ id: spec.id, type: spec.type, takeaway: spec.takeaway, svg });
    console.log(`✓ ${rel} -> ${name}.svg${isApp ? ` + ${name}.ts` : ""}`);
  }

  if (wantIndex) {
    for (const [dir, figs] of Object.entries(byDir)) {
      // never write showcase files inside app/; showcases belong in dev-space
      if (relative(ROOT, dir).startsWith("app")) continue;
      writeFileSync(join(dir, "index.html"), indexHtml(figs));
      console.log(`✓ showcase: ${relative(ROOT, join(dir, "index.html"))}`);
    }
  }
  if (failed) process.exit(1);
}

main();
