import type { AppShortcuts, Shortcut, ShortcutKey } from "../types.ts";

const binding = (platform: "windows" | "macos" | "linux", keys: string[], alternatives?: string[][]): ShortcutKey => ({ platform, keys, ...(alternatives ? { alternatives } : {}) });
const macKeys = (keys: string[]): string[] => keys.map((value) => (value === "Ctrl" ? "Cmd" : value === "Alt" ? "Option" : value));
const common = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: [
    binding("windows", keys, alternatives),
    binding("macos", macKeys(keys), alternatives?.map(macKeys)),
    binding("linux", keys, alternatives),
  ],
  ...(note ? { note } : {}),
});
const same = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: (["windows", "macos", "linux"] as const).map((platform) => binding(platform, keys, alternatives)),
  ...(note ? { note } : {}),
});

