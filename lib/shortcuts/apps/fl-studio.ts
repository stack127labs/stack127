import type { AppShortcuts, Shortcut, ShortcutKey } from "../types.ts";

const platforms = ["windows", "macos"] as const;

const key = (platform: "windows" | "macos", keys: string[]): ShortcutKey => ({ platform, keys });

const pair = (
  id: string,
  action: string,
  windows: string[],
  macos: string[],
  note?: string,
): Shortcut => ({
  id,
  action,
  keys: [key("windows", windows), key("macos", macos)],
  ...(note ? { note } : {}),
});

const shared = (id: string, action: string, keys: string[], note?: string): Shortcut =>
  pair(id, action, keys, keys, note);

const sharedAlternatives = (
  id: string,
  action: string,
  keys: string[],
  alternatives: string[][],
  note?: string,
): Shortcut => ({
  id,
  action,
  keys: platforms.map((platform) => ({ platform, keys, alternatives })),
  ...(note ? { note } : {}),
});

