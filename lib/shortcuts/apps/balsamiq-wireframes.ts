import type { AppShortcuts, Shortcut, ShortcutKey } from "../types.ts";

const binding = (platform: "windows" | "macos", keys: string[], alternatives?: string[][]): ShortcutKey => ({
  platform,
  keys,
  ...(alternatives ? { alternatives } : {}),
});

const both = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: [binding("windows", keys, alternatives), binding("macos", keys, alternatives)],
  ...(note ? { note } : {}),
});

const win = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: [binding("windows", keys, alternatives)],
  ...(note ? { note } : {}),
});

const split = (
  id: string,
  action: string,
  windows: string[],
  macos: string[],
  windowsAlternatives?: string[][],
  macosAlternatives?: string[][],
): Shortcut => ({ id, action, keys: [binding("windows", windows, windowsAlternatives), binding("macos", macos, macosAlternatives)] });

