import type { AppShortcuts, Shortcut, ShortcutKey } from "../types.ts";

const platforms = ["windows", "macos"] as const;

const key = (
  platform: "windows" | "macos",
  keys: string[],
  alternatives?: string[][],
): ShortcutKey => ({
  platform,
  keys,
  ...(alternatives ? { alternatives } : {}),
});

const pair = (
  id: string,
  action: string,
  windows: string[],
  macos: string[],
  windowsAlternatives?: string[][],
  macosAlternatives?: string[][],
  note?: string,
): Shortcut => ({
  id,
  action,
  keys: [
    key("windows", windows, windowsAlternatives),
    key("macos", macos, macosAlternatives),
  ],
  ...(note ? { note } : {}),
});

const shared = (id: string, action: string, keys: string[], note?: string): Shortcut =>
  pair(id, action, keys, keys, undefined, undefined, note);

const mac = (id: string, action: string, keys: string[], note?: string): Shortcut => ({
  id,
  action,
  keys: [key("macos", keys)],
  ...(note ? { note } : {}),
});

