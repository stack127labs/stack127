import type { AppShortcuts, Shortcut, ShortcutKey } from "../types.ts";

const platforms = ["windows", "macos", "linux"] as const;

const bind = (platform: (typeof platforms)[number], keys: string[], alternatives?: string[][]): ShortcutKey => ({
  platform,
  keys,
  ...(alternatives ? { alternatives } : {}),
});

const shared = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: platforms.map((platform) => bind(platform, keys, alternatives)),
  ...(note ? { note } : {}),
});

const desktop = (
  id: string,
  action: string,
  windowsLinux: string[],
  macos: string[],
  note?: string,
): Shortcut => ({
  id,
  action,
  keys: [
    bind("windows", windowsLinux),
    bind("linux", windowsLinux),
    bind("macos", macos),
  ],
  ...(note ? { note } : {}),
});

