import type { AppShortcuts, Shortcut } from "../types.ts";

type Binding = string | string[];
type Row = [id: string, action: string, windows: Binding | null, macos?: Binding | null];
const parse = (value: string) => value.split("+").map((key) => key.trim());
const binding = (platform: "windows" | "macos", value: Binding) => {
  const choices = typeof value === "string" ? [value] : value;
  return {
    platform,
    keys: parse(choices[0]),
    ...(choices.length > 1 ? { alternatives: choices.slice(1).map(parse) } : {}),
  };
};
const rows = (items: Row[]): Shortcut[] =>
  items.map(([id, action, windows, macos = windows]) => ({
    id,
    action,
    keys: [
      ...(windows ? [binding("windows", windows)] : []),
      ...(macos ? [binding("macos", macos)] : []),
    ],
  }));

