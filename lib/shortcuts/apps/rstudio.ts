import { perPlatform } from "../build.ts";
import type { AppShortcuts, Shortcut } from "../types.ts";

const platforms = ["windows", "macos", "linux"] as const;
const desktopPlatforms = ["windows", "macos", "linux"] as const;

const tri = (id: string, action: string, windowsLinux: string[], mac: string[], note?: string): Shortcut => ({
  id,
  action,
  keys: perPlatform(platforms, { windows: windowsLinux, linux: windowsLinux, macos: mac }),
  ...(note ? { note } : {}),
});

const all = (id: string, action: string, keys: string[], note?: string): Shortcut => tri(id, action, keys, keys, note);

const macOnly = (id: string, action: string, keys: string[], note?: string): Shortcut => ({
  id,
  action,
  keys: [{ platform: "macos", keys, ...(note ? { note } : {}) }],
});

