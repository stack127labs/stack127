import type { AppShortcuts, Shortcut } from "../types.ts";

type Row = [id: string, action: string, keys: string[], alternatives?: string[][], note?: string];
const macKeys = (keys: string[]) => keys.map((key) => (key === "Ctrl" ? "Cmd" : key));
const rows = (items: Row[]): Shortcut[] =>
  items.map(([id, action, keys, alternatives, note]) => ({
    id,
    action,
    keys: [
      { platform: "windows", keys, ...(alternatives ? { alternatives } : {}) },
      {
        platform: "macos",
        keys: macKeys(keys),
        ...(alternatives ? { alternatives: alternatives.map(macKeys) } : {}),
      },
    ],
    ...(note ? { note } : {}),
  }));

