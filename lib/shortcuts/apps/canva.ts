import type { AppShortcuts, Shortcut, ShortcutKey } from "../types.ts";

const key = (platform: "windows" | "macos", keys: string[], alternatives?: string[][]): ShortcutKey => ({
  platform,
  keys,
  ...(alternatives ? { alternatives } : {}),
});

const both = (
  id: string,
  action: string,
  windows: string[],
  macos: string[],
  windowsAlternatives?: string[][],
  macosAlternatives?: string[][],
  note?: string,
): Shortcut => ({
  id,
  action,
  keys: [key("windows", windows, windowsAlternatives), key("macos", macos, macosAlternatives)],
  ...(note ? { note } : {}),
});

const shared = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut =>
  both(id, action, keys, keys, alternatives, alternatives, note);

const windows = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: [key("windows", keys, alternatives)],
  ...(note ? { note } : {}),
});

const macos = (id: string, action: string, keys: string[], alternatives?: string[][], note?: string): Shortcut => ({
  id,
  action,
  keys: [key("macos", keys, alternatives)],
  ...(note ? { note } : {}),
});

